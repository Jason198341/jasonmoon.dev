/**
 * 역사 — 한국사 + 세계사가 하나의 스키마를 쓴다 (track 으로만 가름)
 *
 * ⚠️ 별도 스키마로 나누면 동기화(같은 시기에 저쪽에선 무슨 일이?)가 영원히 불가능해진다.
 *
 * 학습 단위는 사건이 아니라 **쟁점 질문(Inquiry)** 이다.
 *   · 사건을 단위로 하면 물을 게 "언제 일어났나"밖에 없어 연도 암기로 붕괴한다.
 *   · 인물을 단위로 하면 위인전 함정 — 구조를 개인의 성품으로 환원한다.
 *
 * 그리고 아빠 예습(HistoryPrep)이 이 과목의 심장이다.
 * 수학의 제1원칙 프로토콜을 역사에 옮기면:
 *   ①출발점(공리) 자리에 **더 안 쪼개지는 전제**가 들어가고
 *   원자들이 그 전제에서 도출되고
 *   인과 사슬이 한 줄로 닫혀야 한다 — 새 재료를 쓰지 않고.
 */

export type Track = 'kr' | 'world';
export type Rank = 'arc' | 'core' | 'side';

export const RANK_LABEL: Record<Rank, string> = {
  arc: '큰 질문', core: '중간 질문', side: '곁가지',
};

/** 확신도 — 역사 서술에서 필수. 표기 없으면 정설로 읽힌다 */
export type Conf = '정설' | '유력' | '추측' | '미해결';

/* ---------------- 인과 링크 ---------------- */
export type Strength = 'decisive' | 'contributing' | 'background';

export const STRENGTH_LABEL: Record<Strength, string> = {
  decisive: '결정적', contributing: '거들었다', background: '배경',
};

export interface CausalLink {
  from: string;
  to: string;
  strength: Strength;
  conf: Conf;
  why: string;
  /** 이 원인을 빼면 어떻게 됐을까 — 정답을 요구하지 않는다. 무게를 재는 연습 */
  ifRemoved?: string;
}

/* ---------------- 장면 ---------------- */
export interface Scene {
  id: string;
  track: Track;
  title: string;
  span: [number] | [number, number];
  /** 지리 과목의 Place id. 장소 없는 사건은 받지 않는다 */
  placeIds: string[];
  what: string;
  /** 당대 사람들이 어떤 제약 안에 있었나 (제1원칙의 "출발점" 자리) */
  constraint?: string;
  conf?: Conf;
}

/* ---------------- 백과 항목 ---------------- */
export type EntryKind = 'person' | 'thing' | 'system' | 'concept';

export interface Entry {
  id: string;
  track: Track;
  kind: EntryKind;
  name: string;
  en?: string;
  one: string;
  body?: string;
  /** 위인전 함정 방지 — 못 한 것, 한계, 양면성 */
  limits?: string;
  conf?: Conf;
  /** 어느 편이었나 (권력 다툼에서) */
  side?: string;
}

/* ---------------- 아빠 예습 : 제1원칙 ----------------
   ★ 이 과목의 심장. 수학 prep 와 같은 정신, 다른 항목. */
export interface HistoryPrep {
  status: 'todo' | 'drafting' | 'ready' | 'taught';
  minutes?: number;
  updated?: string;
  /** ① 출발점 — 더 안 쪼개지는 전제. 이것만으로 나머지가 도출돼야 한다 */
  axioms: string;
  /** ② 원자 — 전제에서 하나씩 도출되는 사실들 */
  atoms: string;
  /** ③ 인과 사슬 — 한 줄로 닫힌다. 새 재료를 쓰지 않는다 */
  chain: string;
  /** 비유 + ▸ 깨지는 지점 (한계를 안 붙이면 오개념을 심는다) */
  analogy?: string;
  /** 흔한 오해 */
  myths?: string;
  /** 이 설명이 틀리려면 무엇이 달라야 하는가 */
  ifWrong?: string;
  /** 한 줄 압축 — 압축이 안 되면 구조가 없는 것이다 */
  compress: string;
  /** 아이에게 던질 확인 질문 */
  questions?: string;
  /** 자기 점검 */
  checklist?: Partial<Record<
    'axiom' | 'undef' | 'leap' | 'naming' | 'analogy' | 'boundary' | 'rederive', boolean>>;
}

/* ---------------- 쟁점 질문 ---------------- */
export interface Inquiry {
  id: string;
  track: Track;
  rank: Rank;
  q: string;
  school?: string;
  sceneIds: string[];
  entryIds?: string[];
  /**
   * 답의 후보들. 하나만 두지 않는다.
   * ⚠️ 상대주의 함정 방지: 각 답에 증거의 무게를 반드시 적는다.
   *    "의견이 갈린다"로 끝내면 아이는 "그럼 아무거나 되네"로 간다.
   */
  answers?: { claim: string; weight: '증거 많음' | '증거 보통' | '증거 약함'; why: string }[];
  /** 아빠가 결국 어느 쪽에 서는가. 회피하지 않는다 */
  dadStance?: string;
  prep?: HistoryPrep;
}

/* ---------------- 동시성 ---------------- */
export interface SyncPoint {
  year: number;
  sceneIds: string[];
  note: string;
}

/* ---------------- 반복 구조 ----------------
   ⚠️ 패턴을 가르치면 아이가 역사를 결정론으로 오해할 수 있다.
      그래서 모든 Pattern 은 broke(패턴이 안 통한 사례)를 반드시 갖는다. */
export interface Pattern {
  id: string;
  name: string;
  steps: string[];
  instances: { label: string; sceneIds: string[]; note?: string }[];
  broke: { label: string; why: string };
}

