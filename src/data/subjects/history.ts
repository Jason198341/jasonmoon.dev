export const byTrack = <T extends { track: Track }>(xs: T[], t: Track) =>
  xs.filter((x) => x.track === t);

export const scenesOf = (inq: Inquiry) =>
  inq.sceneIds.map((id) => SCENES.find((s) => s.id === id)).filter(Boolean) as Scene[];

export const entriesOf = (inq: Inquiry) =>
  (inq.entryIds ?? []).map((id) => ENTRIES.find((e) => e.id === id)).filter(Boolean) as Entry[];

export const linksOf = (sceneId: string) =>
  CAUSAL_LINKS.filter((l) => l.from === sceneId || l.to === sceneId);

export const yearOf = (s: Scene) => s.span[0];

