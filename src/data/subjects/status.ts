/**
 * 작성 상태 게이트 — 전 과목 공통
 *
 * ★ 이 파일이 "아빠가 손으로 채운다"를 가능하게 하는 핵심 장치다.
 *
 * 설계 원칙 하나:
 *   **결핍은 「깨짐」이 아니라 「잠김」이다.**
 *   필드가 비면 그 기능 하나가 회색으로 잠기고, 화면은 정상 렌더된다.
 *   이 원칙이 프레임과 콘텐츠를 완전히 분리한다.
 *
 * 왜 필요한가 — 역사팀 계산:
 *   Core 항목 1개 = 예습 90~150분 + 수업 60분 + 입력 30분 ≈ 3~4.5시간
 *   60개 × 3.5h = 210시간/년
 *   직장인 가용 = 주 4h × 50주 = 200시간
 *   → 여유가 0이다. 여유 0인 계획은 출장 1번, 야근 2주, 감기 1번에 무너진다.
 *   그리고 무너지면 아이가 배우는 건 과목이 아니라 "아빠가 또 안 하네"다.
 *   ★ 이게 콘텐츠 부족보다 훨씬 큰 손실이다.
 *
 * 그래서 검증(필수 필드 강제)은 'ready'로 올릴 때만 발동한다.
 * stub/draft 상태에서는 경고만 하고, 화면에는 정직하게 표시한다.
 */

export type Status =
  | 'stub'    // 제목만. 링크는 살아있고 화면에 회색으로 뜬다
  | 'draft'   // 가르칠 수 있다. 일부 기능 잠김
  | 'ready';  // 필수 필드 전부 채움. 전부 해제

export const STATUS_LABEL: Record<Status, string> = {
  stub: '아직 비어 있음',
  draft: '쓰는 중',
  ready: '준비됨',
};

export const STATUS_COLOR: Record<Status, string> = {
  stub: '#B9BEC7',
  draft: '#D97706',
  ready: '#2F855A',
};

/** stub/draft 항목에 붙는 정직한 안내 문구 */
export const gapNote = (missing: string) =>
  `이 부분은 아직 비어 있어 — 아빠가 채우는 중 (${missing})`;

/**
 * 부작용이 오히려 좋다:
 * 세연이가 "이건 아빠가 만든 것"임을 계속 본다.
 */
export interface Gated {
  status: Status;
  /** 무엇이 없어서 무엇이 잠겼는지 */
  locked?: string[];
}

